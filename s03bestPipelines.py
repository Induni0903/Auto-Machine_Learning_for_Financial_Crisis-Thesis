def set_param_recursive(pipeline_steps, parameter, value):
    """Recursively iterate through all objects in the pipeline and set a given parameter.

    Parameters
    ----------
    pipeline_steps: array-like
        List of (str, obj) tuples from a scikit-learn pipeline or related object
    parameter: str
        The parameter to assign a value for in each pipeline object
    value: any
        The value to assign the parameter to in each pipeline object
    Returns
    -------
    None

    """
    for (_, obj) in pipeline_steps:
        recursive_attrs = ["steps", "transformer_list", "estimators"]
        for attr in recursive_attrs:
            if hasattr(obj, attr):
                set_param_recursive(getattr(obj, attr), parameter, value)
        if hasattr(obj, "estimator"):  # nested estimator
            est = getattr(obj, "estimator")
            if hasattr(est, parameter):
                setattr(est, parameter, value)
        if hasattr(obj, parameter):
            setattr(obj, parameter, value)

def computePredictProba(pipe, xTrain, xTest, yTrain, yTest, random_state=random_state):
    """
    Fit a pipeline and compute predicted probabilities on the test set.

    This function checks whether the provided pipeline implements
    ``predict_proba``. If so, the model is fitted on the training set,
    class probabilities are computed on the test set, and the results
    are returned in a DataFrame. If the pipeline does not support
    ``predict_proba``, an empty DataFrame with the expected columns is
    returned instead.

    Parameters
    ----------
    pipe : sklearn.pipeline.Pipeline or estimator
        A scikit-learn compatible pipeline or estimator.
    xTrain : pandas.DataFrame
        Training feature set.
    xTest : pandas.DataFrame
        Test feature set.
    yTrain : pandas.Series or array-like
        Training target values.
    yTest : pandas.Series or array-like
        Test target values.
    random_state : int, default=random_state
        Seed for reproducibility when fitting the estimator.

    Returns
    -------
    df : pandas.DataFrame
        DataFrame containing:
        - ``yTest`` : True labels from the test set
        - ``yPredProba_0`` : Predicted probability for class 0
        - ``yPredProba_1`` : Predicted probability for class 1

        If ``predict_proba`` is not available, the DataFrame will be
        empty but still include the expected columns.

    Notes
    -----
    - Calls ``pipe.fit`` internally before computing probabilities.
    - Intended for binary classification problems where two probability
      columns are returned.
    """
    if hasattr(pipe, 'predict_proba'):
        pipe.fit(xTrain, yTrain)
        yPredProba = pipe.predict_proba(xTest)
        df = pd.DataFrame({'yTest':yTest, 'yPredProba_0':yPredProba[:,0], 'yPredProba_1':yPredProba[:,1] })
    else:
        log(pipe, 'has no method predict_proba()')
        df = pd.DataFrame({'yTest':[], 'yPredProba_0':[], 'yPredProba_1':[]})
    
    return df
    

