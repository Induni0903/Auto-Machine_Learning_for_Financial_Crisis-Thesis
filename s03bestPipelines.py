def evaluatePipeline(
        pipe, 
        datasetNickName,
    ):
    """
    Train, evaluate, and log results of a machine learning pipeline on a dataset.

    This function loads the dataset, fits the given pipeline, computes
    evaluation metrics, generates data for learning and ROC curves, logs
    the outputs, and produces a learning curve plot as an in-memory buffer.

    Parameters
    ----------
    pipe : sklearn.pipeline.Pipeline or estimator
      The estimator or pipeline implementing `fit` and `predict`. 
    datasetNickName : str
      Identifier for the dataset to load using `geTrainTesttDataset`.
 
    Returns
    -------
    rep : str
        Textual classification report from ``sklearn.metrics.classification_report``.
    f1Macro : float
        Macro-averaged F1 score on the test set.
    figBuffer : io.BytesIO
        A memory buffer containing the PNG image of the learning curve.

    Notes
    -----
    - Logs multiple intermediate results: classification report, learning curve
      data, and ROC curve data.
    - Uses :func:`computeLearningCurveData` for learning curves and
      :func:`computePredictProba` for probability-based evaluation.
    - The function assumes that ``geTrainTesttDataset`` and ``log`` are defined
      elsewhere in the codebase.
    
    """
    xTrain, xTest, yTrain, yTest = geTrainTesttDataset(datasetNickName)

    
    pipe.fit(xTrain, yTrain)
    yPred = pipe.predict(xTest)
    rep = classification_report(yTest, yPred)

    f1Macro = f1_score(yTest, yPred, average='macro')
    
    log(f'Dataset  {datasetNickName}')
    log(pipe)
    log('Classification report\n',rep)
    log('Data for Learning Curves, computed on both train and test set')
    lcDF = computeLearningCurveData(pipe, xTrain, xTest, yTrain, yTest, random_state=random_state)
    log('\n'+lcDF.to_csv(index=False))
    log('Data for Roc Curve computed on the test set')
    ppDF = computePredictProba(pipe, xTrain, xTest, yTrain, yTest, random_state=random_state)
    log('\n'+ppDF.to_csv(index=False))
    log(sep)

    figBuffer = createLearingCurvePlot(lcDF)
    return rep, f1Macro, figBuffer

