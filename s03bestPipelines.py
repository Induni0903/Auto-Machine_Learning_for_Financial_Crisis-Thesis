def geTrainTesttDataset(datasetNickName):
    """
    Generate training and testing datasets for early warning models.

    Depending on the name of the dataset, this function loads and verify the presence of 
    required target variable and covariates and splits the dataset into train and test datsets.

    Parameters
    ----------
    datasetNickName: str
       Name of the dataset configuration. Must be one of:
         * `early_warning_ml` - uses table `cr03_ml` with the base covariates + `crisis0_1` variabel.
         * `early_warning_ml_rolling_window` - uses a table `cr03_ml_rolling` with the base covariates + rolling variables( lagged values (`os1_`, `os2_`, `os3_`, `os4_`) ).

    Returns
    -------
    xTrain :  pandas.DataFrame
        Training feature set (covariates).
    xTest : pandas.DataFrame
        Testing feature set (covariates).
    yTrain : pandas.series
        Training target variable.
    yTest : pandas.series
        Testing target variable.

    Notes
    -----
    -  Drops the `index` column from the dataset if present.
    - Uses `grp` column values (`'balanced_train'` and `'balanced_test'`)
      to create train/test splits.
    - Relies on external variables: `baseCovariates`, `rollingAdditionalCovariates`,
      `targetVarName`, `dbfn`, and function `readDataset`.

    """
    assert datasetNickName in ['early_warning_ml', 'early_warning_ml_rolling_window']
    if datasetNickName == 'early_warning_ml':
        tableName='cr03_ml' 
        rolling=False 
        covariates = baseCovariates + ['crisis0_1']     
    elif datasetNickName == 'early_warning_ml_rolling_window':
        tableName='cr03_ml_rolling'
        rolling=True
        covariates = baseCovariates + rollingAdditionalCovariates

    else:
        log('Unrecognized datasetName')
        return 
    

    dfb = readDataset(
        dbfn = dbfn,
        tableName=tableName
    )

    if 'index' in dfb.columns:
        dfb.drop(columns=['index'], inplace=True)

    # Checking that target variables and covariates are available
    for col in [targetVarName]+covariates:
        assert col in dfb.columns , f'Attribute *{col}* not found'
        

    trainSelectionMask = dfb.grp=='balanced_train'
    testSelectionMask = dfb.grp=='balanced_test'

    xTrain = dfb.loc[trainSelectionMask, covariates]
    xTest = dfb.loc[testSelectionMask, covariates]

    yTrain = dfb.loc[trainSelectionMask, targetVarName]
    yTest = dfb.loc[testSelectionMask, targetVarName]

    return xTrain, xTest, yTrain, yTest

def computeLearningCurveData(pipe, xTrain, xTest, yTrain, yTest, random_state=random_state):
    """
    Compute learning curve performance data for a given estimator pipeline.

    This function evaluates model performance on larger traing samples (equal crisis
    vs. nun-crisis cases). At each sample size, the model is trained and evaluates on
     both training and test sets, producing classification metrics.

    Parameters
    ----------
    pipe : sklearn.pipeline.Pipeline or estimator
      The pipeline implementing `fit` and `predict`.
    xTrain : pandas.DataFrame
      The training feature set(covariates).
    xTest : pandas.DataFrame
      The testing feature set(covariates).
    yTrain : pandas.Series
      Training labels
    yTest : pandass.Series
      Testing labels.
    random_state : random_state
      Random seed for reproducibility when sampling the trainig samples.

    Returns
    -------
    df : pandas.DataFrame
      A dataframe containing performance metrics for different training samples.
      Variables of the dataset:
        - `Num` : number of training samples used.
        - `accuracy_train` : accuracy of the train set
        - `accuracy_test` : accuracy of the test set
        - `precision_train` : precision of the train set
        - `precision_test` : precision of the test set
        - `recall_train` : recall of the train set
        - `recall_test` : recall of the test set 
        - `f1_train` : f1 of the train set
        - `f1_test` : : f1 of the test set

    Raises
    ------
    AssertionError
        If the indices of `xTrain` and `yTrain` are not aligned.

    Notes
    -----
    - Training subsets are balanced: half positive (crisis) and half negative.
    - F1 score is computed using `average='macro'`.
        
    """
    f1weightedLi=[]
    f1unweightedLi=[]
    precisionLi=[]
    recallLi=[]

    nRecords = len (xTrain)
    sampleDimensionLi = [int(nRecords*perc/100) for perc in range(5, 105, 5)]
    performanceLi=[]

    assert (xTrain.index==yTrain.index).all()

    for sampleDimension in sampleDimensionLi:
        halfSample = int(sampleDimension/2)
        # Please, make sure that half are sampled from crisis and half are sampled from non crisis
        indLiAll = yTrain[yTrain==0].sample(halfSample, random_state=random_state).index
        indLi1 = yTrain[yTrain==1].sample(halfSample, random_state=random_state).index
        indLiAll = indLiAll.union(indLi1, sort=True)

        """print(indLiAll)
        print(xTrain.head()) 
        print(yTrain.head())
        print('halfSample', halfSample)
        print(yTrain[indLiAll])

        exit()"""

        xTrainSample = xTrain.loc[indLiAll,:]
        yTrainSample = yTrain[indLiAll]

        di={}
        pipe.fit(xTrainSample, yTrainSample)

        yPredTest = pipe.predict(xTest)
        yPredTrain = pipe.predict(xTrainSample)

        di['Num']=halfSample*2

        di['accuracy_test']=accuracy_score(yTest, yPredTest)
        di['accuracy_train']=accuracy_score(yTrainSample, yPredTrain)
        
        di['precision_test']=precision_score(yTest, yPredTest)
        di['precision_train']=precision_score(yTrainSample, yPredTrain)
        
        di['recall_test']=recall_score(yTest, yPredTest)
        di['recall_train']=recall_score(yTrainSample, yPredTrain)
        
        di['f1_test']=f1_score(yTest, yPredTest, average='macro')
        di['f1_train']=f1_score(yTrainSample, yPredTrain, average='macro')
        

        performanceLi.append(
            di
        )

    df = pd.DataFrame(performanceLi)
    return df

